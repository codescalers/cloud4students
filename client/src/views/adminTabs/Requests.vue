<template>
  <v-container fluid>
    <v-row>
      <v-col cols="12" md="8">
        <v-data-table
          :loading="loading"
          :headers="pendingVouchersHeaders"
          :items="pendingVouchers"
          class="d-flex justify-center elevation-1"
          :hide-default-footer="pendingVouchers == 0"
        >
          <template #[`item.id`]="{ index }"> {{ index + 1 }} </template>

          <template #[`item.name`]="{ item }">
            <div class="d-flex align-center" v-if="item.name">
              <v-avatar color="secondary" size="30" class="mr-2">
                <span class="text-uppercase">{{ userAvatar(item.name) }}</span>
              </v-avatar>
              <div>
                <p>{{ item.name }}</p>
                <p>
                  {{ item.email }}
                </p>
              </div>
            </div>
            <div class="d-flex align-center" v-else>
              <v-avatar color="warning" size="30" class="mr-2">
                <span class="text-uppercase">A</span>
              </v-avatar>
              <div>
                <p>Voucher generated by Admin</p>
              </div>
            </div>
          </template>
          <template #[`item.created_at`]="{ item }">
            {{ timeAgo.format(convertDate(item.created_at)) }}
          </template>
          <template #[`item.balance`]="{ item }">
            {{ item.balance > 0 ? `$${item.balance}` : item.balance }}
          </template>
          <template #[`item.actions`]="{ item }">
            <BaseButton
              color="secondary"
              text="Approve"
              size="small"
              class="mr-1 text-capitalize"
              @click="approveVoucher(item.id, true)"
            />
            <BaseButton
              color="error"
              text="Reject"
              size="small"
              class="text-capitalize"
              @click="approveVoucher(item.id, false)"
            />
          </template>
        </v-data-table>
        <div class="d-flex justify-end">
          <BaseButton
            color="secondary"
            text="Approve All"
            class="my-2"
            :disabled="pendingVouchers > 0"
            @click="approveAllVouchers"
          />
        </div>
      </v-col>
      <v-col cols="12" md="4">
        <v-data-table
          :headers="usersHeaders"
          :items="users"
          class="d-flex justify-center elevation-1"
          :hide-default-footer="users == 0"
        >
          <template #[`item.id`]="{ index }"> {{ index + 1 }} </template>

          <template #[`item.first_name`]="{ item }">
            <div class="d-flex align-center" v-if="item.first_name">
              <v-avatar color="secondary" size="30" class="mr-2">
                <span class="text-uppercase">{{
                  userAvatar(item.first_name)
                }}</span>
              </v-avatar>
              <div>
                <p>{{ item.first_name }}</p>
                <p>
                  {{ item.email }}
                </p>
              </div>
            </div>
            <div v-else>
              <v-avatar color="warning" size="30" class="mr-2">
                <span class="text-uppercase">A</span>
              </v-avatar>
              <div>
                <p>Voucher generated by Admin</p>
              </div>
            </div>
          </template>
          <template #[`item.count.vms`]="{ item }">
            {{ item.count.vms }}
          </template>
          <template #[`item.count.ips`]="{ item }">
            {{ item.count.ips }}
          </template>

          <template #[`item.created_at`]="{ item }">
            <timeago :datetime="item.created_at"></timeago>
          </template>
          <template #[`item.actions`]="{ item }">
            <v-icon class="mr-2">mdi-information</v-icon>
            <v-icon v-if="item.admin" @click="setAdmin(item.email, !item.admin)"
              >mdi-account-key</v-icon
            >
            <v-icon v-else @click="setAdmin(item.email, !item.admin)"
              >mdi-account-lock</v-icon
            >
          </template>
        </v-data-table></v-col
      >
    </v-row>
  </v-container>
  <Toast ref="toast" />
</template>
<script setup>
import { ref, onMounted } from "vue";
import router from "@/router";
import userService from "@/services/userService";
import BaseButton from "@/components/Form/BaseButton.vue";
import Toast from "@/components/Toast.vue";
import TimeAgo from "javascript-time-ago";
import en from "javascript-time-ago/locale/en";
import { storeToRefs } from "pinia";
import { useUserStore } from "@/store/UserStore";

defineProps({
  pendingVouchers: {
    type: Array,
  },
});
const emit = defineEmits("updateVouchers");

TimeAgo.addLocale(en);
const timeAgo = ref(new TimeAgo("en-US"));
const users = ref([]);
const toast = ref(null);
const loading = ref(false);
const store = useUserStore();
const { isAdmin } = storeToRefs(store);

const pendingVouchersHeaders = ref([
  { title: "No", key: "id" },
  { title: "User", key: "name", sortable: false },
  { title: "Created at", key: "created_at" },
  { title: "Reason for Voucher", key: "reason", sortable: false },
  { title: "Balance", key: "balance" },
  { title: "Voucher", key: "voucher" },
  { title: "Actions", key: "actions", sortable: false },
]);

const usersHeaders = ref([
  { title: "No", key: "id", sortable: false },
  { title: "Name", key: "first_name", sortable: false },
  { title: "VMs", key: "count.vms", sortable: false },
  { title: "IPs", key: "count.ips", sortable: false },
  { title: "Actions", key: "actions", sortable: false },
]);

function convertDate(date) {
  return new Date(date);
}

async function getUsers() {
  loading.value = true;
  await userService
    .getUsers()
    .then((response) => {
      const { data } = response.data;
      users.value = data;
    })
    .catch((response) => {
      const { err } = response.response.data;
      toast.value.toast(err, "#FF5252");
    })
    .finally(() => {
      loading.value = false;
    });
}

function userAvatar(name) {
  return name.charAt(0);
}

async function approveVoucher(id, approved) {
  await userService
    .approveVoucher(id, approved)
    .then(async (response) => {
      toast.value.toast(response.data.msg, "#388E3C");
    })
    .catch((response) => {
      const { err } = response.response.data;
      toast.value.toast(err, "#FF5252");
    })
    .finally(() => emit("updateData"));
}

async function approveAllVouchers() {
  await userService
    .approveAllVouchers()
    .then(async (response) => {
      toast.value.toast(response.data.msg, "#388E3C");
    })
    .catch((response) => {
      const { err } = response.response.data;
      toast.value.toast(err, "#FF5252");
    })
    .finally(() => emit("updateData"));
}

async function setAdmin(email, admin) {
  await userService
    .setAdmin(email, admin)
    .then(async (response) => {
      toast.value.toast(response.data.msg, "#388E3C");
      if (!isAdmin) {
        router.push("/");
      }
      await getUsers();
    })
    .catch((response) => {
      const { err } = response.response.data;
      toast.value.toast(err, "#FF5252");
    });
}

onMounted(async () => {
  await getUsers();
});
</script>
